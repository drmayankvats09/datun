/** Total weight = sum of all archetype weights (used for distribution sampling) */
export const TOTAL_ARCHETYPE_WEIGHT = PATIENT_ARCHETYPES.reduce((sum, a) => sum + a.weight, 0);

/** Pick archetype by weighted random — deterministic given seed */
export function pickArchetype(seed: number): PatientArchetype {
  const target = (seed % 1_000_000) * (TOTAL_ARCHETYPE_WEIGHT / 1_000_000);
  let cumulative = 0;
  for (const arch of PATIENT_ARCHETYPES) {
    cumulative += arch.weight;
    if (cumulative >= target) return arch;
  }
  return PATIENT_ARCHETYPES[PATIENT_ARCHETYPES.length - 1]!;
}

/** Filter archetypes by age */
export function getArchetypesForAge(ageYears: number): readonly PatientArchetype[] {
  return PATIENT_ARCHETYPES.filter((a) => ageYears >= a.age.min && ageYears <= a.age.max);
}
