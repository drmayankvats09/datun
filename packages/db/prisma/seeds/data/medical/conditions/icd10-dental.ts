/** Lookup by exact ICD-10 code */
const CONDITION_BY_CODE = new Map(ICD10_DENTAL_CONDITIONS.map((c) => [c.icd10Code, c]));
export function getConditionByIcd10(code: string): DentalCondition | undefined {
  return CONDITION_BY_CODE.get(code);
}

/** Filter by chapter (K00, K01, ...) */
export function getConditionsByChapter(chapter: ConditionChapter): readonly DentalCondition[] {
  return ICD10_DENTAL_CONDITIONS.filter((c) => c.chapter === chapter);
}

/** Filter by urgency */
export function getConditionsByUrgency(urgency: UrgencyLevel): readonly DentalCondition[] {
  return ICD10_DENTAL_CONDITIONS.filter((c) => c.defaultUrgency === urgency);
}

/** Filter by age — returns conditions where given age falls in typical range */
export function getConditionsForAge(ageYears: number): readonly DentalCondition[] {
  return ICD10_DENTAL_CONDITIONS.filter(
    (c) => ageYears >= c.typicalAgeRange.min && ageYears <= c.typicalAgeRange.max,
  );
}

/** Weighted sample by Indian prevalence — pick condition realistic for population */
export function pickRealisticCondition(seed: number, ageYears?: number): DentalCondition {
  const pool = ageYears !== undefined ? getConditionsForAge(ageYears) : ICD10_DENTAL_CONDITIONS;
  const totalWeight = pool.reduce((sum, c) => sum + c.indianPrevalencePer100k, 0);
  let cumulative = 0;
  const target = (seed % 1_000_000) * (totalWeight / 1_000_000);
  for (const cond of pool) {
    cumulative += cond.indianPrevalencePer100k;
    if (cumulative >= target) return cond;
  }
  return pool[pool.length - 1]!;
}
