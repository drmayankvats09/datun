/**
 * Translation keys used when the upload pipeline rejects a file.
 *
 * Memory rule (15 May 2026): user-facing copy NEVER blames the user and
 * NEVER mentions size. These keys redirect with an action-oriented message.
 * Frontend resolves them via `next-intl`. See apps/web/messages/<locale>/media.json.
 */
export const MEDIA_ERROR_KEYS = {
  /** First bytes don't match any allowed image signature (video, zip, exe …). */
  notAnImage: 'media.errors.notAnImage',
  /** Looks like a video file. */
  looksLikeVideo: 'media.errors.looksLikeVideo',
  /** File opens but is corrupted / unreadable. */
  cannotProcess: 'media.errors.cannotProcess',
  /** Per-consultation photo cap reached (5 by default). */
  consultationPhotoLimit: 'media.errors.consultationPhotoLimit',
  /** Per-clinic gallery cap reached. */
  galleryLimit: 'media.errors.galleryLimit',
  /** Upload window expired before client confirmed. */
  uploadExpired: 'media.errors.uploadExpired',
  /** Background processing failed — admin will retry. */
  processingFailed: 'media.errors.processingFailed',
} as const;

export type MediaErrorKey = (typeof MEDIA_ERROR_KEYS)[keyof typeof MEDIA_ERROR_KEYS];
